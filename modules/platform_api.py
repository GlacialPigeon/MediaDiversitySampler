from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable, Protocol


class InstanceLock(Protocol):
    def acquire(self) -> bool: ...
    def release(self) -> None: ...


class PlatformAdapter(Protocol):
    def set_log_callback(self, callback: Any) -> None: ...
    def configure_console(self) -> None: ...
    def clear_screen(self) -> None: ...
    def create_instance_lock(self, path: Path) -> InstanceLock: ...
    def ffprobe_path(self, app_root: Path) -> Path: ...
    def subprocess_process_options(self) -> dict[str, Any]: ...
    def default_excluded_directories(self) -> set[str]: ...

    def remove_outer_quotes(self, value: str | None) -> str: ...
    def path_key(self, value: str) -> str: ...
    def relative_key(self, value: str) -> str: ...
    def relative_is_ancestor(self, parent: str, child: str, allow_equal: bool = False) -> bool: ...
    def normalize_path(self, path: str) -> str: ...
    def resolve_storage(self, path: str, require_directory: bool = False) -> dict[str, Any]: ...
    def canonical_existing_path(self, path: str) -> str: ...
    def paths_equal(self, a: str, b: str) -> bool: ...
    def is_path_ancestor(self, child: str, parent: str, allow_equal: bool = False) -> bool: ...
    def storage_relative_path(self, full_path: str, root_path: str) -> str: ...
    def leaf_label(self, path: str) -> str: ...
    def is_link_or_reparse_point(self, path: str) -> bool: ...
    def no_link_ancestors(self, path: str) -> bool: ...
    def valid_filename_component(self, text: str) -> bool: ...
    def path_parts(self, path: str) -> tuple[str, ...]: ...
    def relative_parts(self, value: str) -> tuple[str, ...]: ...
    def ensure_trailing_separator(self, path: str) -> str: ...
    def valid_managed_relative_path(self, path: str) -> bool: ...
    def source_review_alias(self, raw: str) -> tuple[str, str]: ...
    def source_alias_group_key(self, item: dict[str, Any]) -> str | None: ...
    def source_alias_render_spec(self, kind: str) -> tuple[int, str]: ...
    def adopt_storage_identity(self, desc: dict[str, Any], existing_items: Iterable[dict[str, Any]]) -> dict[str, Any]: ...
    def descriptor_persistence_fields(self, desc: dict[str, Any]) -> dict[str, Any]: ...
    def empty_descriptor_persistence_fields(self) -> dict[str, Any]: ...
    def link_violation_message(self, code: str, path: str | None = None) -> str: ...
    def platform_reason_locale_key(self, reason: str) -> str | None: ...

    def join_path(self, *parts: str) -> str: ...
    def basename(self, path: str) -> str: ...
    def dirname(self, path: str) -> str: ...
    def splitext(self, path: str) -> tuple[str, str]: ...
    def normpath(self, path: str) -> str: ...
    def normcase(self, path: str) -> str: ...
    def isabs(self, path: str) -> bool: ...


_PLATFORM: PlatformAdapter | None = None


def configure_platform(platform: PlatformAdapter) -> None:
    global _PLATFORM
    _PLATFORM = platform


def platform() -> PlatformAdapter:
    if _PLATFORM is None:
        raise RuntimeError("Platform adapter is not configured.")
    return _PLATFORM


def clear_screen() -> None: platform().clear_screen()
def ffprobe_path(app_root: Path) -> Path: return platform().ffprobe_path(app_root)
def subprocess_process_options() -> dict[str, Any]: return platform().subprocess_process_options()
def default_excluded_directories() -> set[str]: return platform().default_excluded_directories()
def remove_outer_quotes(value: str | None) -> str: return platform().remove_outer_quotes(value)
def path_key(value: str) -> str: return platform().path_key(value)
def relative_key(value: str) -> str: return platform().relative_key(value)
def relative_is_ancestor(parent: str, child: str, allow_equal: bool = False) -> bool: return platform().relative_is_ancestor(parent, child, allow_equal)
def normalize_path(path: str) -> str: return platform().normalize_path(path)
def resolve_storage(path: str, require_directory: bool = False) -> dict[str, Any]: return platform().resolve_storage(path, require_directory)
def canonical_existing_path(path: str) -> str: return platform().canonical_existing_path(path)
def paths_equal(a: str, b: str) -> bool: return platform().paths_equal(a, b)
def is_path_ancestor(child: str, parent: str, allow_equal: bool = False) -> bool: return platform().is_path_ancestor(child, parent, allow_equal)
def storage_relative_path(full_path: str, root_path: str) -> str: return platform().storage_relative_path(full_path, root_path)
def leaf_label(path: str) -> str: return platform().leaf_label(path)
def is_link_or_reparse_point(path: str) -> bool: return platform().is_link_or_reparse_point(path)
def no_link_ancestors(path: str) -> bool: return platform().no_link_ancestors(path)
def valid_filename_component(text: str) -> bool: return platform().valid_filename_component(text)
def path_parts(path: str) -> tuple[str, ...]: return platform().path_parts(path)
def relative_parts(value: str) -> tuple[str, ...]: return platform().relative_parts(value)
def ensure_trailing_separator(path: str) -> str: return platform().ensure_trailing_separator(path)
def valid_managed_relative_path(path: str) -> bool: return platform().valid_managed_relative_path(path)
def source_review_alias(raw: str) -> tuple[str, str]: return platform().source_review_alias(raw)
def source_alias_group_key(item: dict[str, Any]) -> str | None: return platform().source_alias_group_key(item)
def source_alias_render_spec(kind: str) -> tuple[int, str]: return platform().source_alias_render_spec(kind)
def adopt_storage_identity(desc: dict[str, Any], existing_items: Iterable[dict[str, Any]]) -> dict[str, Any]: return platform().adopt_storage_identity(desc, existing_items)
def descriptor_persistence_fields(desc: dict[str, Any]) -> dict[str, Any]: return platform().descriptor_persistence_fields(desc)
def empty_descriptor_persistence_fields() -> dict[str, Any]: return platform().empty_descriptor_persistence_fields()
def link_violation_message(code: str, path: str | None = None) -> str: return platform().link_violation_message(code, path)
def platform_reason_locale_key(reason: str) -> str | None: return platform().platform_reason_locale_key(reason)
def join_path(*parts: str) -> str: return platform().join_path(*parts)
def basename(path: str) -> str: return platform().basename(path)
def dirname(path: str) -> str: return platform().dirname(path)
def splitext(path: str) -> tuple[str, str]: return platform().splitext(path)
def normpath(path: str) -> str: return platform().normpath(path)
def normcase(path: str) -> str: return platform().normcase(path)
def isabs(path: str) -> bool: return platform().isabs(path)
